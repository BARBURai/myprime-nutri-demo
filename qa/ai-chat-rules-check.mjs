#!/usr/bin/env node
/* ============================================================================
   שכבה 1: שלושה כללים בצ'אט "ספרי לי מה אכלת", v7.61

   משתתפת, 29 בספטמבר 2026:
   1. כתבה "ויטמין C של Glowi" וקיבלה "אני יכולה לעזור רק בדברים שקשורים לתיעוד
      האוכל", אף שלתוסף יש קלוריות.
   2. הבינה ביקשה ממנה "תצרפי את התמונה", ובשיחה הזאת אין שום דרך לצרף תמונה.
   3. הכוכביות של הדגשה הופיעו על המסך כמו שהן.

   הבדיקה קוראת את ההנחיות מ-src/App.jsx, ומושכת את stripMd משם ומריצה אותה.
   בלי רשת ובלי קריאות AI:  node qa/ai-chat-rules-check.mjs
   ========================================================================== */

import { readFileSync } from "node:fs";

const app = readFileSync("src/App.jsx", "utf8");
let pass = 0, fail = 0;
const ok = (cond, label) => { if (cond) { pass++; console.log("  ✓ " + label); } else { fail++; console.log("  ✗ " + label); } };

const sysLine = app.split("\n").find((l) => l.includes("const system = \"את עוזרת תזונה ידידותית של MyPrime")) || "";
ok(sysLine.length > 0, "נמצאו ההנחיות של צ'אט תיעוד האוכל");

// 1. תוספים
ok(/תוספי תזונה שיש בהם קלוריות/.test(sysLine), "תוסף עם קלוריות נחשב תזונה");
ok(/ואין לסרב להם/.test(sysLine), "ההנחיות אומרות במפורש לא לסרב לתוסף");
ok(/רשומים על האריזה למנה וכמה מנות לקחה/.test(sysLine), "שואלת את הערכים מהאריזה ואת מספר המנות");
ok(/אני מצטערת, אני יכולה לעזור רק בדברים שקשורים לתיעוד האוכל/.test(sysLine), "המשפט הקבוע לנושאים שאינם אוכל נשאר");

// 2. תמונה
ok(/לעולם אל תבקשי ממנה לצרף, לשלוח או לצלם תמונה/.test(sysLine), "הבינה אינה מבקשת תמונה");
// הכלל נכון רק כל עוד אין בצ'אט דרך לצרף תמונה. אם יתווסף כפתור, הבדיקה נופלת
// כדי שמי שמוסיף אותו יחזור גם לכלל הזה.
const aiStart = app.indexOf('{step === "ai" && (');
const aiEnd = app.indexOf('{step === "', aiStart + 20);
const aiBlock = aiStart > 0 ? app.slice(aiStart, aiEnd > aiStart ? aiEnd : aiStart + 20000) : "";
ok(aiBlock.length > 0 && !/type="file"/.test(aiBlock), "במסך הצ'אט אין שדה לצירוף קובץ, ולכן הכלל נכון");

// 3. כוכביות
ok(/בלי כוכביות ובלי שום סימון הדגשה/.test(sysLine), "ההנחיות מבקשות טקסט רגיל");
const m = app.match(/function stripMd\(t\) \{[\s\S]*?\n\}/);
ok(!!m, "נמצאה stripMd");
const stripMd = m ? new Function(m[0] + "; return stripMd;")() : () => "";
ok(stripMd("2. **סלט החסה** - יש בו רוטב?") === "2. סלט החסה - יש בו רוטב?", "הדגשה הופכת לטקסט רגיל");
ok(stripMd("**אחת** ו**שתיים**") === "אחת ושתיים", "כמה הדגשות באותה שורה");
ok(stripMd("כוכבית בודדת ** שנשארה") === "כוכבית בודדת  שנשארה", "זוג כוכביות יתום נמחק");
ok(stripMd("3 * 2 = 6") === "3 * 2 = 6", "כוכבית אחת רגילה אינה נגעת");
ok(stripMd("טקסט רגיל") === "טקסט רגיל", "טקסט בלי הדגשה לא משתנה");
ok(/reply: stripMd\(parsed\.reply \|\| ""\)/.test(app), "התשובה שמוצגת עוברת דרך stripMd");

// ההעתק ב-QA חייב להכיל את אותם כללים. prompt-sync-check משווה את כולו, וזו רק תזכורת ממוקדת.
const qa = readFileSync("qa/run-qa.mjs", "utf8");
ok(qa.includes("לעולם אל תבקשי ממנה לצרף, לשלוח או לצלם תמונה") && qa.includes("תוספי תזונה שיש בהם קלוריות"), "ההעתק ב-qa/run-qa.mjs מעודכן");

console.log(`\n  ${pass}/${pass + fail} עברו`);
process.exit(fail ? 1 : 0);
